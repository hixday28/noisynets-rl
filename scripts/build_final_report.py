def f(value, digits=2):
    return f'{float(value):.{digits}f}'.replace('.', ',').replace('-', '−')


def pm(row, metric='final'):
    return f"{f(row[metric+'_mean'])} ± {f(row[metric+'_seed_sd'])}"


def pct(value):
    return f(float(value) * 100, 1) + ' %'


def interval(row):
    return f"[{f(row['ci95_low'])}; {f(row['ci95_high'])}]"


